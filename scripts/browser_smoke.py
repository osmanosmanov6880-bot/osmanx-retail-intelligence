"""Optional browser QA: pip install playwright && playwright install chromium."""
from pathlib import Path
from playwright.sync_api import sync_playwright

out=Path('qa')
out.mkdir(exist_ok=True)
errors=[]
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1512,'height':950},device_scale_factor=1)
    page.on('pageerror',lambda e:errors.append('desktop: '+str(e)))
    page.goto('http://127.0.0.1:8765/',wait_until='networkidle',timeout=20000)
    page.locator('h1').filter(has_text='Обзор бизнеса').wait_for(timeout=10000)
    page.screenshot(path=str(out/'dashboard-desktop.png'),full_page=True)
    print('DESKTOP headline:',page.locator('h1').first.inner_text())
    page.locator('[data-nav="traffic"]').first.click()
    page.get_by_text('Посетители и конверсия',exact=True).wait_for()
    page.locator('[data-quick="entry"]').click()
    page.get_by_text('Событие записано').wait_for(timeout=7000)
    print('MANUAL input: ok')
    page.locator('[data-nav="demand"]').first.click()
    page.locator('[data-dialog="demand"]').first.click()
    page.locator('#demand-form input[name="product"]').fill('Пальто тестовое')
    page.locator('#demand-form input[name="size"]').fill('XXL')
    page.locator('#demand-form button[type="submit"]').click()
    page.get_by_text('Запрос сохранён').wait_for(timeout=7000)
    print('DEMAND recorded: ok')
    kiosk=browser.new_page(viewport={'width':1080,'height':900},device_scale_factor=1)
    kiosk.on('pageerror',lambda e:errors.append('kiosk: '+str(e)))
    kiosk.goto('http://127.0.0.1:8765/kiosk/central',wait_until='networkidle',timeout=20000)
    kiosk.screenshot(path=str(out/'kiosk-desktop.png'),full_page=True)
    kiosk.locator('[data-kiosk="start"]').click()
    kiosk.locator('[data-rating="5"]').click()
    kiosk.locator('[data-kiosk="next"]').click()
    kiosk.locator('[data-purchased="no"]').click()
    kiosk.locator('[data-reason="size"]').click()
    kiosk.locator('[data-kiosk="next"]').click()
    kiosk.locator('#liked').fill('Очень красивый магазин')
    kiosk.locator('#suggestion').fill('Больше размеров XXL')
    kiosk.locator('#kiosk-form button[type="submit"]').click()
    kiosk.get_by_text('Спасибо!',exact=True).wait_for(timeout=9000)
    print('KIOSK submitted: ok')
    mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
    mobile.on('pageerror',lambda e:errors.append('mobile: '+str(e)))
    mobile.goto('http://127.0.0.1:8765/',wait_until='networkidle',timeout=20000)
    mobile.get_by_text('Обзор бизнеса').wait_for(timeout=10000)
    mobile.screenshot(path=str(out/'dashboard-mobile.png'),full_page=True)
    mobile.goto('http://127.0.0.1:8765/kiosk/central',wait_until='networkidle',timeout=20000)
    mobile.screenshot(path=str(out/'kiosk-mobile.png'),full_page=True)
    print('MOBILE screenshots: ok')
    browser.close()
if errors:
    print('PAGE ERRORS:',errors)
    raise RuntimeError(f'{len(errors)} browser errors')
print('NO PAGE ERRORS')
